export function translateProductName(value: string) {
  if (productNames[value]) return productNames[value];
  let translated = value;
  for (const [ko, en] of Object.entries(productNames).sort(
    ([a], [b]) => b.length - a.length,
  ))
    translated = translated.replace(ko, en);
  return translated
    .replace(/수건걸이/g, "Towel Bar")
    .replace(/휴지걸이/g, "Toilet Paper Holder")
    .replace(/수건선반/g, "Towel Shelf")
    .replace(/크롬/g, "Chrome")
    .replace(/사틴/g, "Satin")
    .replace(/블랙/g, "Black")
    .replace(/무광/g, "Matte");
}

export function translateText(value: string) {
  if (english[value]) return english[value];
  const productImage = value.match(/^(.+) 제품 이미지$/);
  if (productImage)
    return `${translateProductName(productImage[1])} product image`;
  const detail = value.match(/^(.+) 상세 보기$/);
  if (detail) return `View ${translateProductName(detail[1])} details`;
  const imageNumber = value.match(/^(.+) 이미지 (\d+) 보기$/);
  if (imageNumber)
    return `View ${translateProductName(imageNumber[1])} image ${imageNumber[2]}`;
  const finish = value.match(/^마감: (.+)$/);
  if (finish)
    return `Finish: ${finish[1]
      .split(", ")
      .map((item) => english[item] ?? item)
      .join(", ")}`;
  const model = value.match(/^모델 (.+)$/);
  if (model) return `Model ${model[1]}`;
  const count = value.match(/^등록 제품 (\d+)개$/);
  if (count) return `${count[1]} products`;
  const dealerCount = value.match(/^총 (\d+)개의 대리점이 있습니다\.$/);
  if (dealerCount) return `${dealerCount[1]} dealers found.`;
  const totalCount = value.match(/^총 (\d+)개 제품$/);
  if (totalCount) return `${totalCount[1]} products`;
  const viewCount = value.match(/^(\d+)개 제품 보기$/);
  if (viewCount) return `View ${viewCount[1]} products`;
  const countFirst = value.match(/^(\d+)개 제품$/);
  if (countFirst) return `${countFirst[1]} products`;
  const category = value.match(/^카테고리: (.+)$/);
  if (category) return `Category: ${english[category[1]] ?? category[1]}`;
  const collection = value.match(/^(.+) 컬렉션$/);
  if (collection) return `${translateProductName(collection[1])} Collection`;
  const home = value.match(/^(.+) 홈$/);
  if (home) return `${translateProductName(home[1])} home`;
  const translated = translateProductName(value);
  if (translated !== value) return translated;
  if (/[가-힣]/.test(value) && (value.length > 18 || /[.요다]$/.test(value))) {
    return "English translation pending — refer to the Korean source.";
  }
  return value;
}
